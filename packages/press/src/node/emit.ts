import { relative, resolve } from "node:path"
import { slash } from "./project"
import { assertSerializableMetadata } from "./serialization"
import type { ProjectSnapshot } from "./types"

const banner = "// Generated by @yuzur1ha/press. Do not edit.\n"
const literal = (value: unknown) => JSON.stringify(value, null, 2)
function modulePath(root: string, file: string) {
  const path = slash(relative(root, file))
  return path.startsWith(".") ? path : `./${path}`
}
export function emit(snapshot: ProjectSnapshot) {
  const { documents, outputDir, root, config } = snapshot
  for (const document of documents)
    assertSerializableMetadata(document.metadata, document.key)
  const typeImport = config.metadataType
    ? `import type { ${config.metadataType.name} as DocumentMetadata } from ${literal(modulePath(outputDir, resolve(root, config.metadataType.from)))}\n`
    : "type DocumentMetadata = unknown\n"
  const keys = documents.map(({ key }) => literal(key)).join(" | ") || "never"
  const ids =
    [...new Set(documents.map(({ id }) => id))]
      .sort()
      .map(literal)
      .join(" | ") || "never"
  const load = (source: string) =>
    `import(${literal(modulePath(outputDir, resolve(root, source)))})`
  const entries = documents
    .map(
      (document) => `${literal(document.key)}: {
    id: ${literal(document.id)},
    ${document.locale ? `locale: ${literal(document.locale)},` : ""}
    metadata: ${literal(document.metadata)},
    load: () => ${load(document.source)}
  }`,
    )
    .join(",\n")
  const manifest = `${banner}${typeImport}
import type { DocumentKey } from "./documents"
export const documents = {
${entries}
} satisfies Record<DocumentKey, {
  id: string
  locale?: string
  metadata: DocumentMetadata
  load: () => Promise<{default: import("react").ComponentType}>
}>
export default documents
`
  const loaders = documents
    .map(({ key, source }) => `${literal(key)}: () => ${load(source)}`)
    .join(",\n")
  const files: Record<string, string> = {
    "documents.d.ts": `${banner}export type DocumentId = ${ids}\nexport type DocumentKey = ${keys}\n`,
    "manifest.ts": manifest,
    "loaders.ts": `${banner}export default {\n${loaders}\n}\n`,
    "index.json":
      literal(
        documents.map(({ source, id, key, route, locale, metadata }) => ({
          source,
          id,
          key,
          ...(route ? { route } : {}),
          ...(locale ? { locale } : {}),
          metadata,
        })),
      ) + "\n",
  }
  const locales = [
    ...new Set(documents.flatMap(({ locale }) => (locale ? [locale] : []))),
  ].sort()
  for (const locale of locales) {
    if (!/^[a-z0-9-]+$/.test(locale))
      throw new Error(`Invalid generated locale: ${locale}`)
    const metadata = documents
      .filter((document) => document.locale === locale)
      .map((document) => document.metadata)
    files[`metadata-${locale}.ts`] =
      `${banner}${typeImport}const metadata: DocumentMetadata[] = ${literal(metadata)}\nexport default metadata\n`
  }
  const metadataLoaders = locales
    .map(
      (locale) =>
        `${literal(locale)}: () => import(${literal(`./metadata-${locale}`)})`,
    )
    .join(",\n")
  files["metadata.ts"] = `${banner}export default {\n${metadataLoaders}\n}\n`
  return files
}
